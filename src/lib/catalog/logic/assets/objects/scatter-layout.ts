/** Unit-square origins for a loose knot, a line along a deck, or two knots around a gap. */
export function scatterLayout(n: number, v: number, landing: boolean): XY[] {
	if (v === 1 && n === 15) {
		const offsets = [
			0, 0.39, 0.05, 0.46, 0.12, 0.56, 0.21, 0.66, 0.32, 0.78, 0.43, 0.9, 0.54, 1, 0.6
		];
		return offsets.map((y, i) => [i / 14, y]);
	}
	if (v === 1)
		return Array.from({ length: n }, (_, i) => [
			i / (n - 1),
			0.5 - 0.5 * Math.cos((2 * Math.PI * i) / (n - 1))
		]);
	if (landing && v === 0) return landingKnot;
	const plan = (v === 0 ? knots : pairs)[n];
	return plan.map(([x, y]) => [x, landing ? 1 - y : y]);
}
