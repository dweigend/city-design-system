/**
 * Generates src/lib/catalog/data/altstaedte.ts: path networks of four old towns as SVG paths,
 * each a 400 × 400 m excerpt around the measurement center, at the scale of the growth demo.
 * Source: frozen OSM extracts under data/osm/altstaedte (ODbL 1.0).
 * Usage: bun scripts/altstadt-umrisse.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const GROESSE = 400;
const STAEDTE = ['Siena', 'Regensburg', 'Fès', 'Marrakesch'];
const WURZEL = 'data/osm/altstaedte';
/** Walkable paths; these excerpts have hardly any roads, and those count as alleys. */
const WEGE = new Set([
	'pedestrian',
	'footway',
	'residential',
	'service',
	'steps',
	'path',
	'living_street',
	'tertiary',
	'secondary',
	'primary',
	'unclassified',
	'track'
]);

type P = [number, number];
type Messung = { name: string; lat: number; lon: number };
type Element = {
	type: string;
	tags?: Record<string, string>;
	geometry?: { lat: number; lon: number }[];
};

const messwerte: Messung[] = JSON.parse(readFileSync(`${WURZEL}/messwerte.json`, 'utf8'));

/** Clip a segment to the square [0, G]² (Liang–Barsky); null if it lies outside. */
function kuerze(a: P, b: P): [P, P] | null {
	let t0 = 0,
		t1 = 1;
	const dx = b[0] - a[0],
		dy = b[1] - a[1];
	for (const [p, q] of [
		[-dx, a[0]],
		[dx, GROESSE - a[0]],
		[-dy, a[1]],
		[dy, GROESSE - a[1]]
	]) {
		if (p === 0) {
			if (q < 0) return null;
			continue;
		}
		const r = q / p;
		if (p < 0) t0 = Math.max(t0, r);
		else t1 = Math.min(t1, r);
		if (t0 > t1) return null;
	}
	return [
		[a[0] + t0 * dx, a[1] + t0 * dy],
		[a[0] + t1 * dx, a[1] + t1 * dy]
	];
}

/** Douglas–Peucker with a tolerance in meters. */
function vereinfache(pts: P[], tol: number): P[] {
	if (pts.length < 3) return pts;
	const [a, b] = [pts[0], pts[pts.length - 1]];
	const l = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
	let max = 0,
		idx = 0;
	for (let i = 1; i < pts.length - 1; i++) {
		const d = Math.abs((b[0] - a[0]) * (a[1] - pts[i][1]) - (a[0] - pts[i][0]) * (b[1] - a[1])) / l;
		if (d > max) [max, idx] = [d, i];
	}
	if (max <= tol) return [a, b];
	return [
		...vereinfache(pts.slice(0, idx + 1), tol).slice(0, -1),
		...vereinfache(pts.slice(idx), tol)
	];
}

const f = (v: number) => (Math.round(v * 2) / 2).toString();
const ausgabe: { name: string; pfad: string }[] = [];
for (const name of STAEDTE) {
	const m = messwerte.find((x) => x.name === name);
	if (!m) throw new Error(`No measurement center for ${name}`);
	const roh: { elements: Element[] } = JSON.parse(readFileSync(`${WURZEL}/${name}.json`, 'utf8'));
	const kx = Math.cos((m.lat * Math.PI) / 180) * 111320,
		ky = 110540;
	const projiziere = (g: { lat: number; lon: number }): P => [
		(g.lon - m.lon) * kx + GROESSE / 2,
		-(g.lat - m.lat) * ky + GROESSE / 2
	];
	const teile: string[] = [];
	for (const e of roh.elements) {
		if (e.type !== 'way' || !e.geometry || !WEGE.has(e.tags?.highway ?? '')) continue;
		const pts = e.geometry.map(projiziere);
		let lauf: P[] = [];
		const schliesse = () => {
			const v = vereinfache(lauf, 0.6);
			if (v.length > 1) teile.push('M' + v.map((p) => `${f(p[0])} ${f(p[1])}`).join('L'));
			lauf = [];
		};
		for (let i = 0; i < pts.length - 1; i++) {
			const s = kuerze(pts[i], pts[i + 1]);
			if (!s) {
				schliesse();
				continue;
			}
			const letzter = lauf[lauf.length - 1];
			if (!letzter || Math.hypot(letzter[0] - s[0][0], letzter[1] - s[0][1]) > 1e-6) {
				schliesse();
				lauf.push(s[0]);
			}
			lauf.push(s[1]);
		}
		schliesse();
	}
	ausgabe.push({ name, pfad: teile.join('') });
}

const datei = `/**
 * Path networks of four old towns, each 400 × 400 m around the measurement center, as an SVG path
 * at the scale of the growth demo (x east, y south, meters). Generated by scripts/altstadt-umrisse.ts
 * from the OSM extracts in data/osm/altstaedte. Do not edit by hand.
 * Map data © OpenStreetMap contributors, ODbL 1.0.
 */
export type AltstadtId = ${ausgabe.map((a) => `'${a.name.toLowerCase().replace('è', 'e')}'`).join(' | ')};
export const altstadtWege: { id: AltstadtId; name: string; pfad: string }[] = [
${ausgabe.map((a) => `\t{ id: '${a.name.toLowerCase().replace('è', 'e')}', name: '${a.name}', pfad: '${a.pfad}' }`).join(',\n')}
];
export const altstadtLizenz = 'Map data © OpenStreetMap contributors, ODbL 1.0';
`;
writeFileSync('src/lib/catalog/data/altstaedte.ts', datei);
